import { useState } from "react";
import { toast } from "react-toastify";
import { exportAnalyticsRequest } from "../../api/analyticsApi.js";
import Button from "../common/Button.jsx";
import Modal from "../common/Modal.jsx";

const reportTypes = ["overview", "hiring-funnel", "candidates", "jobs", "interviews", "interviewers", "emails", "recruiters", "skills"];

const ExportAnalyticsModal = ({ open, onClose, filters = {} }) => {
  const [reportType, setReportType] = useState("overview");
  const [loading, setLoading] = useState(false);
  const [filename, setFilename] = useState("");

  const download = async () => {
    setLoading(true);
    try {
      const response = await exportAnalyticsRequest({ ...filters, reportType, format: "csv" });
      const disposition = response.headers?.["content-disposition"] || "";
      const match = disposition.match(/filename="([^"]+)"/);
      const name = match?.[1] || `hiresmart-${reportType}-analytics.csv`;
      const url = URL.createObjectURL(response.data);
      const link = document.createElement("a");
      link.href = url;
      link.download = name;
      link.click();
      URL.revokeObjectURL(url);
      setFilename(name);
      toast.success("Analytics report exported");
    } catch (error) {
      toast.error(error.response?.data?.message || "Export failed");
    } finally {
      setLoading(false);
    }
  };

  return (
    <Modal open={open} onClose={onClose} title="Export analytics report">
      <div className="space-y-4">
        <label className="block text-sm font-semibold text-slate-700">
          Report type
          <select className="mt-1 w-full rounded-md border border-slate-300 px-3 py-2" value={reportType} onChange={(event) => setReportType(event.target.value)}>
            {reportTypes.map((type) => <option key={type} value={type}>{type}</option>)}
          </select>
        </label>
        <p className="text-sm text-slate-500">CSV exports are generated by the backend and sanitized against spreadsheet formula injection.</p>
        {filename ? <p className="rounded-md bg-emerald-50 p-3 text-sm font-semibold text-emerald-700">Downloaded {filename}</p> : null}
        <div className="flex justify-end gap-2">
          <Button type="button" variant="outline" onClick={onClose}>Close</Button>
          <Button type="button" loading={loading} onClick={download}>Export CSV</Button>
        </div>
      </div>
    </Modal>
  );
};

export default ExportAnalyticsModal;
